import cv2
import numpy as np

# 1. Создаем черный холст 300x300
img = np.zeros((300, 300), dtype=np.uint8)

# 2. Рисуем идеальный белый квадрат 100x100 в центре (координаты от 100 до 200)
img[100:200, 100:200] = 255

# 3. Добавляем черные дыры внутрь квадрата (шум 2-3 пикселя)
img[120:123, 120:123] = 0
img[170:172, 150:152] = 0
img[140:142, 175:177] = 0

# 4. Добавляем белый шум вокруг квадрата (точки снаружи)
np.random.seed(42) # Фиксируем сид, чтобы шум всегда был одинаковым
noise_x = np.random.randint(0, 300, 50)
noise_y = np.random.randint(0, 300, 50)
for x, y in zip(noise_x, noise_y):
    # Проверяем, чтобы шум не попал внутрь самого квадрата
    if not (100 <= x <= 200 and 100 <= y <= 200):
        img[y:y+2, x:x+2] = 255

# 5. Делаем разрывы краев (стираем пиксели на границах квадрата)
img[100:105, 140:145] = 0  # Разрыв верхней грани
img[150:155, 200] = 0      # Разрыв правой грани
img[195:200, 110:115] = 0  # Разрыв нижней грани

# Сохраняем результат
cv2.imwrite('noisy_square.png', img)
print("Изображение 'noisy_square.png' успешно создано!")